// Regenerates emojis.ts: `node generate-emojis.ts` (needs network).
import { writeFile } from 'node:fs/promises';
import { selectEmojis } from './filter.ts';
import type { RawEmoji } from './types.ts';

const VERSION = '17.0.0';
const SOURCE = `https://cdn.jsdelivr.net/npm/emojibase-data@${VERSION}/en/data.json`;

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`${SOURCE}: HTTP ${response.status}`);
}
const emojis = selectEmojis((await response.json()) as RawEmoji[]);

const rows = emojis.map((entry) => `  ${JSON.stringify(entry)},`).join('\n');
const output = `import type { Emoji } from './types.ts';

// Generated by generate-emojis.ts from emojibase-data@${VERSION} (MIT). Do not edit.
export const EMOJIS = [
${rows}
] satisfies readonly Emoji[];
`;

await writeFile(new URL('./emojis.ts', import.meta.url), output);
console.log(`wrote ${emojis.length} emojis`);
